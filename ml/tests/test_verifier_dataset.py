def patient(number, family):
    text = f"Befunde:<BR>Die Läsion ist links und misst {number + 20} mm."
    normal = text.replace("<BR>", "\n")
    quote = normal.split("\n")[1]
    return {
        "patient": {"id": f"fixture-{number}"},
        "family": family,
        "documents": [{"metadata": {"id": f"doc-{number}", "date": "2024-05-03"}, "text": text}],
        "labels": {
            "facts": [
                {
                    "id": f"f-{number}",
                    "documentId": f"doc-{number}",
                    "kind": "imaging",
                    "labelEn": "Lesion",
                    "attrs": {"value": number + 20, "unit": "mm", "side": "left"},
                    "assertion": "present",
                    "temporalStatus": "stated",
                    "eventDate": None,
                    "datePrecision": None,
                    "start": len("Befunde:\n"),
                    "end": len(normal),
                    "quote": quote,
                }
            ],
            "mutations": [],
        },
    }


def test_patient_and_family_leakage_and_balance(tmp_path):
    source = tmp_path / "sample"
    source.mkdir()
    families = {}
    for number in range(1000):
        family = f"authored-family-{number}"
        families.setdefault(family_split(family), []).append(family)
    chosen = [families[split][i] for split in ("train", "valid", "test") for i in range(3)]
    with (source / "patients.jsonl").open("w") as handle:
        for number, family in enumerate(chosen):
            handle.write(json.dumps(patient(number, family)) + "\n")
    out = tmp_path / "dataset"
    # The production datasheet is regenerated by the actual builder; tests keep it isolated.
    import verifier.build_dataset as module

    original = module.VERIFIER_DIR
    module.VERIFIER_DIR = tmp_path
    try:
        counts = build([source], out, limit=30)
    finally:
        module.VERIFIER_DIR = original
    seen_patients, seen_families = set(), set()
    for split in ("train", "valid", "test"):
        rows = list(read_jsonl(out / f"{split}.examples.jsonl"))
        assert rows
        patients, families = {r["patientId"] for r in rows}, {r["family"] for r in rows}
        assert not patients & seen_patients
        assert not families & seen_families
        seen_patients |= patients
        seen_families |= families
        assert len(set(Counter(r["label"] for r in rows).values())) == 1
        assert counts[split]["rows"] == len(rows)
        if split != "test":
            assert all(row["mutation"] not in {"date_shift", "assertion_flip"} for row in rows)


def test_exact_engine_span_bridge_and_context():
    row = patient(1, "style-a")
    with Bridge() as bridge:
        prepared = bridge.call(op="patient", row=row)
    document, fact = prepared["documents"][0], prepared["facts"][0]
    passage = passage_for(document, fact)
    assert passage["section"] == "Befunde"
    assert passage["text"] == fact["quote"]
    assert "left" in fact["claim"]
    fact["end"] -= 1
    with pytest.raises(ValueError, match="quote"):
        passage_for(document, fact)


def test_balancing_deduplicates():
    rows = [
        {"label": label, "claim": f"{label}-{index}", "passages": []}
        for label in ("supported", "unsupported", "contradicted")
        for index in range(7)
    ]
    selected = balanced(rows + rows, 12, 7)
    assert len(selected) == 12
    assert Counter(row["label"] for row in selected) == dict.fromkeys(
        ("supported", "unsupported", "contradicted"), 4
    )


def test_prompt_overlap_is_reserved_for_test_first():
    row = {"claim": "Synthetic claim", "passages": [{"text": "Synthetic source"}]}
    groups = {split: [row.copy()] for split in ("train", "valid", "test")}
    assert remove_prompt_overlap(groups) == {"valid": 1, "train": 1}
    assert groups["train"] == groups["valid"] == []
    assert groups["test"] == [row]


def test_mutations_change_only_explicit_attributes():
    fact = {
        "attrs": {"side": "left", "value": 22},
        "eventDate": None,
        "assertion": "present",
        "kind": "imaging",
        "temporalStatus": "stated",
    }
    changes = dict(perturbations("Lesion 22 mm (left)", fact))
    assert changes["side_flip"] == "Lesion 22 mm (right)"
    assert changes["number_change"] == "Lesion 29 mm (left)"


def test_metrics_penalise_unavailable():
    result = metrics(
        [
            {"label": "supported", "prediction": "unavailable", "latencyMs": 1},
            {"label": "unsupported", "prediction": "unsupported", "latencyMs": 3},
        ]
    )
    assert result["coverage"] == 0.5
    assert result["classes"]["supported"]["recall"] == 0
    assert result["errors"] == 1


