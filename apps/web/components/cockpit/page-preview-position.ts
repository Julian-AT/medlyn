export function highlightClasses(box: PagePreviewBox): string | null {
  if (
    !Object.values(box).every(Number.isFinite) ||
    box.x0 < 0 ||
    box.y0 < 0 ||
    box.x1 > 1 ||
    box.y1 > 1 ||
    box.x1 <= box.x0 ||
    box.y1 <= box.y0
  )
    return null;
  const left = Math.floor(box.x0 * 100);
  const top = Math.floor(box.y0 * 100);
  const width = Math.ceil(box.x1 * 100) - left;
  const height = Math.ceil(box.y1 * 100) - top;
  return [LEFT[left], TOP[top], WIDTH[width], HEIGHT[height]].join(" ");
}
