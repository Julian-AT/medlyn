def test_generated_rows_reference_exact_final_spans():
    if not (VERIFIER_DIR / "datasets/manifest.json").exists():
        pytest.skip("Synthetic dataset has not been built")
    rows = [
        row
        for split in ("train", "valid", "test")
        for row in read_jsonl(VERIFIER_DIR / f"datasets/{split}.examples.jsonl")
    ]
    wanted = {row["patientId"] for row in rows}
    manifest = json.loads((VERIFIER_DIR / "datasets/manifest.json").read_text())
    facts = {}
    for snapshot in read_jsonl(VERIFIER_DIR / "datasets/source-snapshots.jsonl"):
        patient_id = snapshot["patientId"]
        if patient_id not in wanted:
            continue
        prepared = snapshot["prepared"]
        documents = {doc["id"]: doc for doc in prepared["documents"]}
        for fact in prepared["facts"]:
            passage_for(documents[fact["documentId"]], fact)
            facts[(patient_id, fact["id"])] = fact
        wanted.remove(patient_id)
    assert not wanted
    for row in rows:
        fact = facts[(row["patientId"], row["factId"])]
        assert (row["documentId"], row["start"], row["end"], row["quoteHash"]) == (
            fact["documentId"],
            fact["start"],
            fact["end"],
            digest(fact["quote"]),
        )
        if row["mutation"] == "none":
            assert row["claim"] == fact["claim"]
    for split in ("train", "valid"):
        selected = list(read_jsonl(VERIFIER_DIR / f"datasets/{split}.examples.jsonl"))
        assert not {row["mutation"] for row in selected} & set(manifest["heldOutMutationTypes"])
        assert all(
            row["family"].split(":")[0] not in ("dictated", "structured") for row in selected
        )


def test_training_prompt_matches_non_thinking_inference_and_fits_window():
    if not (VERIFIER_DIR / "datasets/train.jsonl").exists():
        pytest.skip("Synthetic dataset has not been built")
    from transformers import AutoTokenizer

    snapshots = VERIFIER_DIR.parent / ".hf/hub/models--mlx-community--Qwen3-1.7B-4bit/snapshots"
    if not snapshots.exists():
        pytest.skip("Base tokenizer is not cached")
    tokenizer = AutoTokenizer.from_pretrained(str(next(snapshots.iterdir())))
    for split in ("train", "valid", "test"):
        for row in read_jsonl(VERIFIER_DIR / f"datasets/{split}.jsonl"):
            assert len(tokenizer.apply_chat_template(row["messages"], return_dict=False)) <= 512
    row = next(read_jsonl(VERIFIER_DIR / "datasets/train.jsonl"))
    full = tokenizer.apply_chat_template(row["messages"], tokenize=False)
    prefix = tokenizer.apply_chat_template(
        row["messages"][:-1], tokenize=False, add_generation_prompt=True, enable_thinking=False
    )
    assert full.startswith(prefix + row["messages"][-1]["content"])
