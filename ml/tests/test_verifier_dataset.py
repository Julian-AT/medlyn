def test_generated_dataset_has_no_split_leakage():
    if not (VERIFIER_DIR / "datasets/manifest.json").exists():
        pytest.skip("Run the dataset builder after synthetic data arrives")
    seen_patients, seen_families = set(), set()
    seen_prompts = set()
    for name in ("train", "valid", "test"):
        rows = list(read_jsonl(VERIFIER_DIR / f"datasets/{name}.examples.jsonl"))
        patients, families = {row["patientId"] for row in rows}, {row["family"] for row in rows}
        assert not patients & seen_patients
        assert not families & seen_families
        assert "patient-0000-0001" not in patients
        prompts = {
            digest(json.dumps([row["claim"], row["passages"]], sort_keys=True)) for row in rows
        }
        assert not prompts & seen_prompts
        seen_prompts |= prompts
        assert len(set(Counter(row["label"] for row in rows).values())) <= 1
        seen_patients |= patients
        seen_families |= families


